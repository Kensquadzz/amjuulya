// Generates src/fonts.css from installed @fontsource packages:
// only the subsets the app needs (latin, latin-ext, cyrillic, cyrillic-ext)
// and only woff2 (every target browser supports it).
// Run after changing the font list: npm run fonts
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const FONTS = [
  ['poppins', [300, 400, 500, 600, 700, 800, 900], true],
  ['montserrat', [300, 400, 500, 600, 700, 800, 900], true],
  ['inter', [200, 300, 400, 500, 600, 700, 800, 900], true],
  ['unbounded', [300, 400, 500, 600, 700, 800, 900], false],
  ['space-grotesk', [300, 400, 500, 600, 700], false],
  ['manrope', [200, 300, 400, 500, 600, 700, 800], false],
  ['syne', [400, 500, 600, 700, 800], false],
  ['oswald', [300, 400, 500, 600, 700], false],
  ['roboto-condensed', [300, 400, 500, 600, 700, 800], true],
  ['orelega-one', [400], false],
  ['bebas-neue', [400], false],
  ['playfair-display', [400, 500, 600, 700, 800, 900], true],
  ['instrument-serif', [400], true],
  ['jetbrains-mono', [300, 400, 500, 600, 700, 800], true],
];
const KEEP = new Set(['latin', 'latin-ext', 'cyrillic', 'cyrillic-ext']);
const out = ['/* GENERATED by scripts/build-fonts.mjs — do not edit.',
  '   Self-hosted fonts from Fontsource (SIL Open Font License 1.1). unicode-range',
  '   makes the browser fetch only the subsets a text uses (latin / cyrillic). */'];
for (const [pkg, weights, italic] of FONTS) {
  for (const w of weights) {
    for (const style of italic ? ['', '-italic'] : ['']) {
      const file = `node_modules/@fontsource/${pkg}/${w}${style}.css`;
      if (!existsSync(file)) throw new Error('missing ' + file);
      const css = readFileSync(file, 'utf8');
      for (const m of css.matchAll(/\/\* ([\w-]+) \*\/\s*(@font-face\s*\{[^}]*\})/g)) {
        const subset = m[1].replace(`${pkg}-`, '').replace(new RegExp(`-${w}-(normal|italic)$`), '');
        if (!KEEP.has(subset)) continue;
        const face = m[2]
          .replace(/,\s*url\([^)]*\.woff\)\s*format\('woff'\)/, '')
          .replace(/url\(\.\/files\//, `url(../node_modules/@fontsource/${pkg}/files/`);
        out.push(face);
      }
    }
  }
}
writeFileSync('src/fonts.css', out.join('\n') + '\n');
console.log('faces:', out.length - 1);
