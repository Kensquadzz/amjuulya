// Regenerates lib/migrations.js from migrations/*.sql (run after adding or editing a migration).
// The SQL is embedded in JS so the serverless bundle always contains it — no runtime file reads.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const dir = fileURLToPath(new URL('../migrations/', import.meta.url));
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
const body = files.map((f) => `  { name: ${JSON.stringify(f)}, sql: ${JSON.stringify(readFileSync(dir + f, 'utf8'))} },`).join('\n');
writeFileSync(fileURLToPath(new URL('../lib/migrations.js', import.meta.url)),
  `// GENERATED by scripts/sync-migrations.mjs from migrations/*.sql — do not edit by hand.\nexport const MIGRATIONS = [\n${body}\n];\n`);
console.log(`lib/migrations.js: ${files.length} migrations`);
