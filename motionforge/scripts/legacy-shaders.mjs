// Fingerprints every built-in shader source that ever shipped (from git
// history of src/engine/shaders/) so saved projects holding an unedited older
// copy can be upgraded to the current source on load.
// Usage: node scripts/legacy-shaders.mjs  (writes src/engine/shaders/legacy.ts)
import { execSync } from 'node:child_process';
import { mkdtempSync, writeFileSync, mkdirSync, readdirSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

const fnv = (s) => { let h = 0x811c9dc5; for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 0x01000193); } return (h >>> 0).toString(16).padStart(8, '0'); };
const tmp = mkdtempSync(join(tmpdir(), 'mf-legacy-'));

/** Write a shader folder to a temp dir (imports given .ts extensions for Node) and load its SHADERS. */
async function load(tag, files) {
  const sub = join(tmp, tag, 'shaders');
  mkdirSync(sub, { recursive: true });
  writeFileSync(join(tmp, tag, 'types.ts'), 'export type BlendMode = string;\n');
  for (const [name, src] of files) writeFileSync(join(sub, name), src.replace(/from '(\.\.?\/[\w/]+)'/g, "from '$1.ts'"));
  return (await import(pathToFileURL(join(sub, 'library.ts')).href)).SHADERS;
}

const here = 'src/engine/shaders';
const cur = await load('current', readdirSync(here).filter((f) => f.endsWith('.ts')).map((f) => [f, readFileSync(join(here, f), 'utf8')]));
const current = new Set(cur.map((s) => fnv(s.source)));
const commits = execSync(`git log --format=%H -- ./${here}`, { encoding: 'utf8' }).trim().split('\n');
const map = {};
for (const c of commits) {
  const names = execSync(`git ls-tree --name-only ${c} ./${here}/`, { encoding: 'utf8' }).trim().split('\n').map((f) => f.split('/').pop());
  const files = names.filter((n) => n.endsWith('.ts')).map((n) => [n, execSync(`git show ${c}:./${here}/${n}`, { encoding: 'utf8' })]);
  for (const s of await load(c, files)) { const h = fnv(s.source); if (!current.has(h)) map[h] = s.id; }
}
const body = Object.entries(map).sort().map(([h, id]) => `  '${h}': '${id}',`).join('\n');
writeFileSync(`${here}/legacy.ts`, `// Generated by scripts/legacy-shaders.mjs — do not edit.
// FNV-1a fingerprints of built-in shader sources from earlier releases, mapped
// to the shader id whose current source replaces them when a project loads.
export const LEGACY_SHADERS: Record<string, string> = {
${body}
};

export function fingerprint(s: string): string {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 0x01000193); }
  return (h >>> 0).toString(16).padStart(8, '0');
}
`);
console.log(Object.keys(map).length, 'legacy sources from', commits.length, 'commits');
