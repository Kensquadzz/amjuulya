// Fingerprints every built-in shader source that ever shipped (from git
// history of src/engine/shaders/library.ts) so saved projects holding an
// unedited older copy can be upgraded to the current source on load.
// Usage: node scripts/legacy-shaders.mjs  (writes src/engine/shaders/legacy.ts)
import { execSync } from 'node:child_process';
import { mkdtempSync, writeFileSync, mkdirSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

const fnv = (s) => { let h = 0x811c9dc5; for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 0x01000193); } return (h >>> 0).toString(16).padStart(8, '0'); };
const commits = execSync('git log --format=%H -- src/engine/shaders/library.ts', { encoding: 'utf8' }).trim().split('\n');
const dir = mkdtempSync(join(tmpdir(), 'mf-legacy-'));
const cur = await import(pathToFileURL(join(process.cwd(), 'src/engine/shaders/library.ts')).href);
const current = new Set(cur.SHADERS.map((s) => fnv(s.source)));
const map = {};
for (const c of commits) {
  const sub = join(dir, c, 'shaders');
  mkdirSync(sub, { recursive: true });
  writeFileSync(join(dir, c, 'types.ts'), 'export type BlendMode = string;\n');
  writeFileSync(join(sub, 'library.ts'), execSync(`git show ${c}:./src/engine/shaders/library.ts`, { encoding: 'utf8' }));
  const mod = await import(pathToFileURL(join(sub, 'library.ts')).href);
  for (const s of mod.SHADERS) { const h = fnv(s.source); if (!current.has(h)) map[h] = s.id; }
}
const body = Object.entries(map).sort().map(([h, id]) => `  '${h}': '${id}',`).join('\n');
writeFileSync('src/engine/shaders/legacy.ts', `// Generated by scripts/legacy-shaders.mjs — do not edit.
// FNV-1a fingerprints of built-in shader sources from earlier releases, mapped
// to the shader id whose current source replaces them when a project loads.
export const LEGACY_SHADERS: Record<string, string> = {
${body}
};

export function fingerprint(s: string): string {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 0x01000193); }
  return (h >>> 0).toString(16).padStart(8, '0');
}
`);
console.log(Object.keys(map).length, 'legacy sources from', commits.length, 'commits');
